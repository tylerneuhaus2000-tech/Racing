import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'race-control', 'data', 'rennleiter_driver_pool_v4.csv');
const rulesSource = path.join(root, 'race-control', 'data', 'rennleiter_development_rules_v4.json');
const output = path.join(root, 'race-control', 'driver-pool-v4.js');

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some(value => value !== '')) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const headers = rows.shift().map((value, i) => i === 0 ? value.replace(/^\uFEFF/, '') : value);
  if (headers.length !== 73 || rows.some(value => value.length !== headers.length)) {
    throw new Error(`CSV schema mismatch: expected 73 columns, got ${headers.length}`);
  }
  return rows.map(values => Object.fromEntries(headers.map((key, i) => [key, values[i]])));
}

const records = parseCsv(fs.readFileSync(source, 'utf8'));
const ids = new Set(), names = new Set();
for (const record of records) {
  if (!record.driver_id || !record.name || ids.has(record.driver_id)) throw new Error(`Missing or duplicate driver id: ${record.driver_id}`);
  const name = record.name.trim().toLocaleLowerCase('en');
  if (names.has(name)) throw new Error(`Duplicate driver name: ${record.name}`);
  for (const [field, min, max, required] of [
    ['f1_skill_game', 0, 100, true], ['potential_game', 0, 100, true], ['age_2026_11_18', 0, 100, false],
    ['development_start_age_game', 0, 100, false], ['f1_min_wait_seasons_game', 0, 80, false],
    ['development_gain_per_season_game', 0, 100, false], ['development_decline_per_season_game', 0, 100, false],
    ['annual_salary_expectation_usd_game', 0, 1e10, false], ['release_fee_usd_game', 0, 1e10, false],
  ]) {
    const raw = record[field];
    if (raw === '' && !required) continue;
    const value = Number(raw);
    if (!Number.isFinite(value) || value < min || value > max) throw new Error(`Invalid ${field} for ${record.driver_id}: ${raw}`);
  }
  ids.add(record.driver_id); names.add(name);
}
if (records.length !== 463) throw new Error(`Expected 463 source records, got ${records.length}`);
fs.writeFileSync(output, `/* Generated by tools/import-race-control-driver-pool.mjs; source fields preserved verbatim. */\nconst DRIVER_POOL_V4=${JSON.stringify(records)};\n`);
const rules = JSON.parse(fs.readFileSync(rulesSource, 'utf8'));
if (rules.schema_version !== 4 || rules.skill_storage !== 'integer hundredths internally; initial f1_skill_game and potential_game are integer points') {
  throw new Error('Unexpected development rules schema.');
}
fs.appendFileSync(output, `const DRIVER_DEVELOPMENT_RULES_V4=${JSON.stringify(rules)};\n`);
console.log(`Imported ${records.length} unique drivers with ${Object.keys(records[0]).length} source fields.`);
