#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'assets/tracks/sachsenring.centerline.json');
const outputPath = path.join(root, 'assets/tracks/sachsenring.js');
const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

if (!Array.isArray(source.pts) || source.pts.length < 100) {
  throw new Error('Sachsenring-Centerline fehlt oder ist unvollstaendig.');
}

const track = {
  id: 'sachsenring',
  name: 'Sachsenring',
  sub: 'Grand-Prix-Kurs · 3,53 km · 14 Kurven · starkes Hoehenprofil',
  meshUrl: 'assets/tracks/sachsenring.glb',
  mesh: {
    offset: source.meshOffset,
    rawSurface: true,
    light: { sun: 0.95, hemi: 0.8, exposure: 1 }
  },
  halfWidth: 7.5,
  sky: 0x9fc3eb,
  hill: 0x5e8a42,
  grass: [0x4e8b3a, 0x407531],
  wallDist: 22,
  kerbW: 3,
  vergeW: 10,
  startFinishPct: 0,
  startGridPct: 99,
  env: 'forest',
  noWalls: true,
  pts: source.pts
};

const banner = `/* Generated by tools/build-sachsenring-track.mjs from
   sachsenring.centerline.json. Do not edit the point list by hand. */\n`;
const output = `${banner}TRACKS.push(${JSON.stringify(track)});\n`;
fs.writeFileSync(outputPath, output);
console.log(`Wrote ${path.relative(root, outputPath)} (${source.pts.length} points)`);
