#!/usr/bin/env node
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';

const threeFile=process.argv[2];
const trackId=process.argv[3]||'silverstone-gp';
const classType=process.argv[4]||'gt3';
const output=process.argv[5]||`assets/tracks/${trackId}-ai.js`;
if(!threeFile)throw Error('Usage: node tools/train-ai-from-world-record.mjs THREE_FILE [track] [class] [output]');
const THREE=await import(path.resolve(threeFile));
const html=fs.readFileSync('gt3-web-racer.html','utf8');
const slice=(a,b)=>{const start=html.indexOf(a),end=html.indexOf(b,start);if(start<0||end<0)throw Error(`Missing marker ${a}`);return html.slice(start,end);};
const context=vm.createContext({THREE:THREE.default||THREE,console,Math,performance:{now:()=>0}});
vm.runInContext([
  slice('const G = 9.81;','class Input {'),
  slice('class Track {','class Particles {'),
  `Track.prototype.buildRoad=Track.prototype.buildKerbs=Track.prototype.buildVerge=Track.prototype.buildWalls=
   Track.prototype.buildPitLane=Track.prototype.buildStartFinish=Track.prototype.buildEnvironment=
   Track.prototype.buildBrakingMarkers=Track.prototype.buildIdealLine=Track.prototype.buildTvCams=
   Track.prototype.buildMeshTrack=function(){};`
].join('\n'),context);
for(const file of ['assets/tracks.js','assets/tracks/redbull-ring.js','assets/tracks/monza-mesh.js','assets/tracks/sachsenring.js'])
  vm.runInContext(fs.readFileSync(file,'utf8'),context,{filename:file});
context.trackId=trackId;
const track=vm.runInContext(`(()=>{const def=TRACKS.find(t=>t.id===trackId);if(!def)throw Error('Unknown track '+trackId);const t=Object.create(Track.prototype);Object.assign(t,{def,halfW:def.halfWidth,kerbW:def.kerbW||1.4,wallDist:def.wallDist||(def.halfWidth+13)});t.buildSpline();return t})()`,context);

const endpoint='https://firestore.googleapis.com/v1/projects/gridline-bf8c9/databases/(default)/documents:runQuery';
const body={structuredQuery:{from:[{collectionId:'times'}],where:{fieldFilter:{field:{fieldPath:'trackId'},op:'EQUAL',value:{stringValue:trackId}}},limit:500}};
const response=await fetch(endpoint,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(body)});
if(!response.ok)throw Error(`Firestore HTTP ${response.status}`);
const value=v=>{
  if(!v)return null;
  if('stringValue'in v)return v.stringValue;
  if('integerValue'in v)return Number(v.integerValue);
  if('doubleValue'in v)return Number(v.doubleValue);
  if('arrayValue'in v)return (v.arrayValue.values||[]).map(value);
  if('mapValue'in v)return Object.fromEntries(Object.entries(v.mapValue.fields||{}).map(([k,x])=>[k,value(x)]));
  return null;
};
const docs=(await response.json()).filter(r=>r.document).map(r=>Object.fromEntries(Object.entries(r.document.fields).map(([k,v])=>[k,value(v)])))
  .filter(r=>String(r.classType).toLowerCase()===classType&&r.replay?.flat?.length)
  .sort((a,b)=>a.timeMs-b.timeMs);
if(!docs.length)throw Error(`No replay for ${trackId}/${classType}`);
const record=docs[0],flat=record.replay.flat,N=track.N;
const lineSum=new Float64Array(N),speedSum=new Float64Array(N),count=new Uint32Array(N);
let idx=0,best=Infinity;
for(let i=0;i<N;i++){
  const dx=flat[1]-track.samples[i].pos.x,dz=flat[2]-track.samples[i].pos.z,d=dx*dx+dz*dz;
  if(d<best){best=d;idx=i;}
}
for(let i=0;i<flat.length;i+=9){
  const pos={x:flat[i+1],z:flat[i+2]};
  const q=track.query(pos,idx);idx=q.idx;
  if(Math.abs(q.lat)>track.halfW+2)continue;
  lineSum[idx]+=q.lat;speedSum[idx]+=Math.max(0,flat[i+5]);count[idx]++;
}
const line=Array(N).fill(null),speed=Array(N).fill(null);
for(let i=0;i<N;i++)if(count[i]){line[i]=lineSum[i]/count[i];speed[i]=speedSum[i]/count[i];}
function fillCircular(values){
  const known=[];for(let i=0;i<N;i++)if(values[i]!=null)known.push(i);
  if(!known.length)throw Error('Replay did not map to track');
  for(let k=0;k<known.length;k++){
    const a=known[k],b=known[(k+1)%known.length],span=(b-a+N)%N||N;
    for(let d=1;d<span;d++){const t=d/span;values[(a+d)%N]=values[a]*(1-t)+values[b]*t;}
  }
}
fillCircular(line);fillCircular(speed);
function smooth(values,radius,passes){
  for(let pass=0;pass<passes;pass++){
    const copy=values.slice();
    for(let i=0;i<N;i++){let sum=0,w=0;for(let d=-radius;d<=radius;d++){const weight=radius+1-Math.abs(d);sum+=copy[(i+d+N)%N]*weight;w+=weight;}values[i]=sum/w;}
  }
}
smooth(line,4,2);smooth(speed,3,1);
for(let i=0;i<N;i++)line[i]=+Math.max(-track.halfW+1.2,Math.min(track.halfW-1.2,line[i])).toFixed(3);
for(let i=0;i<N;i++)speed[i]=+speed[i].toFixed(2);
const profile={source:'cloud-world-record',trackId,classType,timeMs:record.timeMs,carId:record.carId,driver:record.name,
  generatedAt:new Date().toISOString(),line,speed};
const js=`/* Generated by tools/train-ai-from-world-record.mjs. */\n(()=>{const t=TRACKS.find(x=>x.id===${JSON.stringify(trackId)});if(t){t.aiProfiles=t.aiProfiles||{};t.aiProfiles[${JSON.stringify(classType)}]=${JSON.stringify(profile)};}})();\n`;
fs.writeFileSync(output,js);
console.log(JSON.stringify({output,N,recordMs:record.timeMs,carId:record.carId,frames:flat.length/9}));
