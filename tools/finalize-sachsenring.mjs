#!/usr/bin/env node
/* Einmaliger Abschluss-Schritt nach track-osm-fit.mjs: nimmt die frisch
   gefittete centerline.json (bereits zentriert, Hoehe schon aus dem Modell
   gesampelt — kein weiteres Snapping noetig) und
     1) findet die echte Start/Ziel-Linie ueber die startgreen/startred-Mesh-Geometrie
     2) rotiert die Punktliste so, dass Index 0 auf der Linie liegt
     3) schreibt assets/tracks/sachsenring.js im Spiel-Format */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { MeshoptDecoder } from 'meshoptimizer';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'assets/tracks/sachsenring.centerline.json'), 'utf8'));
const outputPath = path.join(root, 'assets/tracks/sachsenring.js');

const doc = await new NodeIO().registerExtensions(ALL_EXTENSIONS)
  .registerDependencies({ 'meshopt.decoder': MeshoptDecoder })
  .read(path.join(root, 'assets/tracks/sachsenring.glb'));

const lights = [], road = [];
for (const node of doc.getRoot().listNodes()) {
  const matrix = node.getWorldMatrix();
  for (const primitive of node.getMesh()?.listPrimitives() || []) {
    const name = primitive.getMaterial()?.getName() || '';
    if (!/^(roada|rdta|start(green|red))/i.test(name)) continue;
    const position = primitive.getAttribute('POSITION');
    const vertices = [];
    for (let i = 0; i < position.getCount(); i++) {
      const p = position.getElement(i, []);
      const point = [
        matrix[0]*p[0]+matrix[4]*p[1]+matrix[8]*p[2]+matrix[12]+source.meshOffset[0],
        matrix[2]*p[0]+matrix[6]*p[1]+matrix[10]*p[2]+matrix[14]+source.meshOffset[2],
        matrix[1]*p[0]+matrix[5]*p[1]+matrix[9]*p[2]+matrix[13]+source.meshOffset[1]
      ];
      vertices.push(point);
    }
    if (/^start/i.test(name)) lights.push(...vertices);
    else {
      const indices = primitive.getIndices();
      for (let i=0; i<(indices?.getCount() || vertices.length); i+=3) {
        road.push([0,1,2].map(k => vertices[indices ? indices.getScalar(i+k) : i+k]));
      }
    }
  }
}
if (!lights.length) throw new Error('Start lights missing');
if (!road.length) throw new Error('Road surface missing');

/* Die OSM-Linie liefert den Grundriss, ihre Hoehenwerte waren stellenweise
   mehrere Meter vom sichtbaren Asphalt entfernt. */
let maxHeightCorrection = 0, surfaceHits = 0;
source.pts = source.pts.map(point => {
  const heights = [];
  for (const [a,b,c] of road) {
    const det=(b[1]-c[1])*(a[0]-c[0])+(c[0]-b[0])*(a[1]-c[1]);
    if(Math.abs(det)<1e-8) continue;
    const u=((b[1]-c[1])*(point[0]-c[0])+(c[0]-b[0])*(point[1]-c[1]))/det;
    const v=((c[1]-a[1])*(point[0]-c[0])+(a[0]-c[0])*(point[1]-c[1]))/det;
    if(u>=-0.001 && v>=-0.001 && u+v<=1.001) heights.push(u*a[2]+v*b[2]+(1-u-v)*c[2]);
  }
  if(!heights.length) return point;
  const y=heights.sort((a,b)=>Math.abs(a-point[2])-Math.abs(b-point[2]))[0];
  /* Bei Bruecken kann ein anderer Streckenabschnitt dieselben X/Z-Koordinaten
     belegen. Grosse Abweichungen deshalb nicht automatisch uebernehmen. */
  if(Math.abs(y-point[2])>2) return point;
  surfaceHits++;
  maxHeightCorrection=Math.max(maxHeightCorrection,Math.abs(y-point[2]));
  return [point[0],point[1],Math.round(y*1000)/1000];
});
const start = lights.reduce((a,p)=>[a[0]+p[0]/lights.length, a[1]+p[1]/lights.length], [0,0]);
let startIndex = 0;
source.pts.forEach((p,i)=>{
  if (Math.hypot(p[0]-start[0], p[1]-start[1]) < Math.hypot(source.pts[startIndex][0]-start[0], source.pts[startIndex][1]-start[1])) startIndex = i;
});
source.pts = source.pts.slice(startIndex).concat(source.pts.slice(0, startIndex));
console.log({ start, startIndex, surfaceHits, maxHeightCorrection });

const track = {
  id: 'sachsenring',
  name: 'Sachsenring',
  sub: 'Grand-Prix-Kurs · 3,53 km · 14 Kurven · starkes Hoehenprofil',
  meshUrl: 'assets/tracks/sachsenring.glb',
  mesh: { offset: source.meshOffset, rawSurface: true, light: { sun: 0.95, hemi: 0.8, exposure: 1 } },
  halfWidth: 7.5,
  sky: 0x9fc3eb,
  hill: 0x5e8a42,
  grass: [0x4e8b3a, 0x407531],
  wallDist: 22,
  kerbW: 3,
  vergeW: 10,
  startFinishPct: 0,
  startGridPct: 99,
  env: 'forest',
  noWalls: true,
  pts: source.pts
};

const banner = `/* Generated by tools/track-osm-fit.mjs + tools/finalize-sachsenring.mjs from
   sachsenring.centerline.json. Do not edit the point list by hand. */\n`;
fs.writeFileSync(outputPath, `${banner}TRACKS.push(${JSON.stringify(track)});\n`);
console.log(`Wrote ${path.relative(root, outputPath)} (${source.pts.length} points)`);
